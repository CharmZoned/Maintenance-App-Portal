-- LD-30 (partial): PaymentReceipts metadata + private payment-receipts bucket.
-- Depends on Payments + PaymentIntents settlement path. Does not alter inquiries.

CREATE TABLE IF NOT EXISTS public."PaymentReceipts" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  payment_id bigint NOT NULL REFERENCES public."Payments"(id) ON DELETE CASCADE,
  storage_path text NOT NULL,
  file_name text NOT NULL,
  content_type text NOT NULL DEFAULT 'application/pdf',
  byte_size bigint,
  generated_at timestamptz NOT NULL DEFAULT now(),
  is_test_data boolean NOT NULL DEFAULT false,
  CONSTRAINT payment_receipts_payment_unique UNIQUE (payment_id),
  CONSTRAINT payment_receipts_storage_path_unique UNIQUE (storage_path),
  CONSTRAINT payment_receipts_path_shape
    CHECK (storage_path ~ ('^receipts/' || payment_id::text || '/[^/]+$'))
);

CREATE INDEX IF NOT EXISTS payment_receipts_payment_idx
  ON public."PaymentReceipts" (payment_id);

COMMENT ON TABLE public."PaymentReceipts" IS
  'Receipt file metadata for settled Payments; objects live in payment-receipts bucket.';

ALTER TABLE public."PaymentReceipts" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."PaymentReceipts" FORCE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION private.can_select_payment_receipt(p_payment_id bigint)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
  SELECT EXISTS (
    SELECT 1
    FROM public."Payments" AS pay
    JOIN public."RentCharges" AS c ON c.id = pay.charge_id
    JOIN public."Leases" AS l ON l.id = c.lease_id
    WHERE pay.id = p_payment_id
      AND (
        private.is_admin()
        OR private.landlord_owns_unit(l.unit_id)
        OR l.unit_id IS NOT DISTINCT FROM private.current_tenant_unit_id()
        OR private.staff_assigned_to_unit(l.unit_id)
      )
  );
$function$;

REVOKE ALL ON FUNCTION private.can_select_payment_receipt(bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION private.can_select_payment_receipt(bigint) TO authenticated, service_role;

DROP POLICY IF EXISTS payment_receipts_select ON public."PaymentReceipts";
CREATE POLICY payment_receipts_select
  ON public."PaymentReceipts"
  FOR SELECT
  TO authenticated
  USING (private.can_select_payment_receipt(payment_id));

DROP POLICY IF EXISTS payment_receipts_admin_insert ON public."PaymentReceipts";
CREATE POLICY payment_receipts_admin_insert
  ON public."PaymentReceipts"
  FOR INSERT
  TO authenticated
  WITH CHECK (private.is_staff_or_admin());

DROP POLICY IF EXISTS payment_receipts_admin_delete ON public."PaymentReceipts";
CREATE POLICY payment_receipts_admin_delete
  ON public."PaymentReceipts"
  FOR DELETE
  TO authenticated
  USING (private.is_admin());

GRANT SELECT, INSERT, DELETE ON public."PaymentReceipts" TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public."PaymentReceipts" TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public."PaymentReceipts_id_seq" TO authenticated, service_role;

