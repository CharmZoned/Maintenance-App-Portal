-- Phase 5: PropertyDocuments + private property-documents bucket
-- Additive. Does not alter inquiries.
--
-- Visibility (admin-marked only): tenant | staff | landlord
-- Hierarchical read:
--   staff     → staff/admin
--   landlord  → staff/admin + owning landlord
--   tenant    → staff/admin + owning landlord + tenant of property (unit match when set)

-- ── Table ─────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public."PropertyDocuments" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  property_id bigint NOT NULL
    REFERENCES public."Properties"(id) ON DELETE CASCADE,
  unit_id bigint
    REFERENCES public."Units"(id) ON DELETE CASCADE,
  title text NOT NULL,
  file_name text NOT NULL,
  content_type text,
  byte_size bigint,
  storage_path text NOT NULL,
  visibility text NOT NULL DEFAULT 'staff'
    CHECK (visibility = ANY (ARRAY['tenant'::text, 'staff'::text, 'landlord'::text])),
  uploaded_by_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  uploaded_by_role public.app_role,
  notes text,
  is_test_data boolean NOT NULL DEFAULT false,
  CONSTRAINT property_documents_storage_path_unique UNIQUE (storage_path),
  CONSTRAINT property_documents_path_shape
    CHECK (storage_path ~ ('^' || property_id::text || '/[^/]+$'))
);

CREATE INDEX IF NOT EXISTS property_documents_property_idx
  ON public."PropertyDocuments" (property_id, created_at DESC);

CREATE INDEX IF NOT EXISTS property_documents_unit_idx
  ON public."PropertyDocuments" (unit_id)
  WHERE unit_id IS NOT NULL;

COMMENT ON TABLE public."PropertyDocuments" IS
  'Property (and optional unit) documents; visibility admin-marked: tenant|staff|landlord.';

-- Unit must belong to the same property when set
CREATE OR REPLACE FUNCTION private.enforce_property_document_unit()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
BEGIN
  IF NEW.unit_id IS NULL THEN
    RETURN NEW;
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public."Units" AS u
    WHERE u.id = NEW.unit_id
      AND u.property_id = NEW.property_id
  ) THEN
    RAISE EXCEPTION 'unit_id must belong to property_id';
  END IF;

  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS trg_property_documents_unit ON public."PropertyDocuments";
CREATE TRIGGER trg_property_documents_unit
  BEFORE INSERT OR UPDATE OF property_id, unit_id ON public."PropertyDocuments"
  FOR EACH ROW
  EXECUTE FUNCTION private.enforce_property_document_unit();

-- Only admin may mark/change visibility away from staff default
CREATE OR REPLACE FUNCTION private.protect_property_document_visibility()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_admin boolean;
BEGIN
  IF auth.uid() IS NULL THEN
    RETURN NEW;
  END IF;

  v_admin := private.is_admin();

  IF TG_OP = 'INSERT' THEN
    IF NOT v_admin AND NEW.visibility IS DISTINCT FROM 'staff' THEN
      RAISE EXCEPTION 'Only admins can set document visibility';
    END IF;
    RETURN NEW;
  END IF;

  IF NEW.visibility IS DISTINCT FROM OLD.visibility AND NOT v_admin THEN
    RAISE EXCEPTION 'Only admins can change document visibility';
  END IF;

  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS trg_property_documents_visibility ON public."PropertyDocuments";
CREATE TRIGGER trg_property_documents_visibility
  BEFORE INSERT OR UPDATE OF visibility ON public."PropertyDocuments"
  FOR EACH ROW
  EXECUTE FUNCTION private.protect_property_document_visibility();

-- ── Helpers ───────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION private.can_select_property_document(
  p_property_id bigint,
  p_unit_id bigint,
  p_visibility text
)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
  SELECT
    CASE
      WHEN private.is_staff_or_admin() THEN true
      WHEN private.current_role() = 'landlord'::public.app_role
        AND p_visibility = ANY (ARRAY['landlord'::text, 'tenant'::text])
        AND EXISTS (
          SELECT 1
          FROM public."Properties" AS p
          WHERE p.id = p_property_id
            AND p.landlord_id = private.current_landlord_id()
        )
      THEN true
      WHEN private.current_role() = 'tenant'::public.app_role
        AND p_visibility = 'tenant'
        AND p_property_id IS NOT DISTINCT FROM private.current_tenant_property_id()
        AND (
          p_unit_id IS NULL
          OR p_unit_id IS NOT DISTINCT FROM private.current_tenant_unit_id()
        )
      THEN true
      ELSE false
    END;
$function$;

CREATE OR REPLACE FUNCTION private.can_manage_property_documents()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
  SELECT private.is_staff_or_admin();
$function$;

COMMENT ON FUNCTION private.can_select_property_document(bigint, bigint, text) IS
  'Read ACL for PropertyDocuments by visibility + role scope.';
COMMENT ON FUNCTION private.can_manage_property_documents() IS
  'Staff/admin may upload/update/delete property documents.';

-- ── RLS ───────────────────────────────────────────────────────────

ALTER TABLE public."PropertyDocuments" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."PropertyDocuments" FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS property_documents_select ON public."PropertyDocuments";
CREATE POLICY property_documents_select
  ON public."PropertyDocuments"
  FOR SELECT
  TO authenticated
  USING (
    private.can_select_property_document(property_id, unit_id, visibility)
  );

DROP POLICY IF EXISTS property_documents_insert ON public."PropertyDocuments";
CREATE POLICY property_documents_insert
  ON public."PropertyDocuments"
  FOR INSERT
  TO authenticated
  WITH CHECK (
    private.can_manage_property_documents()
    AND uploaded_by_user_id = auth.uid()
    AND uploaded_by_role IS NOT DISTINCT FROM private.current_role()
    AND storage_path ~ ('^' || property_id::text || '/[^/]+$')
    AND (
      private.is_admin()
      OR visibility = 'staff'
    )
  );

DROP POLICY IF EXISTS property_documents_update ON public."PropertyDocuments";
CREATE POLICY property_documents_update
  ON public."PropertyDocuments"
  FOR UPDATE
  TO authenticated
  USING (private.can_manage_property_documents())
  WITH CHECK (
    private.can_manage_property_documents()
    AND (
      private.is_admin()
      OR visibility = 'staff'
    )
  );

DROP POLICY IF EXISTS property_documents_delete ON public."PropertyDocuments";
CREATE POLICY property_documents_delete
  ON public."PropertyDocuments"
  FOR DELETE
  TO authenticated
  USING (private.can_manage_property_documents());

-- ── Storage bucket ────────────────────────────────────────────────

INSERT INTO storage.buckets (id, name, public, file_size_limit)
VALUES ('property-documents', 'property-documents', false, 20971520)
ON CONFLICT (id) DO UPDATE
SET public = EXCLUDED.public,
    file_size_limit = EXCLUDED.file_size_limit;

DROP POLICY IF EXISTS property_documents_storage_select ON storage.objects;
CREATE POLICY property_documents_storage_select
  ON storage.objects
  FOR SELECT
  TO authenticated
  USING (
    bucket_id = 'property-documents'
    AND EXISTS (
      SELECT 1
      FROM public."PropertyDocuments" AS doc
      WHERE doc.storage_path = name
        AND private.can_select_property_document(
          doc.property_id,
          doc.unit_id,
          doc.visibility
        )
    )
  );

DROP POLICY IF EXISTS property_documents_storage_insert ON storage.objects;
CREATE POLICY property_documents_storage_insert
  ON storage.objects
  FOR INSERT
  TO authenticated
  WITH CHECK (
    bucket_id = 'property-documents'
    AND private.can_manage_property_documents()
    AND name ~ '^[0-9]+/[^/]+$'
  );

DROP POLICY IF EXISTS property_documents_storage_update ON storage.objects;
CREATE POLICY property_documents_storage_update
  ON storage.objects
  FOR UPDATE
  TO authenticated
  USING (
    bucket_id = 'property-documents'
    AND private.can_manage_property_documents()
  )
  WITH CHECK (
    bucket_id = 'property-documents'
    AND private.can_manage_property_documents()
  );

DROP POLICY IF EXISTS property_documents_storage_delete ON storage.objects;
CREATE POLICY property_documents_storage_delete
  ON storage.objects
  FOR DELETE
  TO authenticated
  USING (
    bucket_id = 'property-documents'
    AND private.can_manage_property_documents()
  );
