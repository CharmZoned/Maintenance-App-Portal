-- ── PaymentIntents ────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public."PaymentIntents" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  charge_id bigint NOT NULL REFERENCES public."RentCharges"(id) ON DELETE RESTRICT,
  tenant_id bigint NOT NULL REFERENCES private.tenants(id) ON DELETE RESTRICT,
  amount numeric NOT NULL CHECK (amount > 0),
  method text NOT NULL CHECK (method = ANY (ARRAY['card'::text, 'ach'::text, 'zelle'::text])),
  status text NOT NULL DEFAULT 'pending'
    CHECK (status = ANY (ARRAY[
      'pending'::text,
      'processing'::text,
      'requires_action'::text,
      'succeeded'::text,
      'failed'::text,
      'canceled'::text,
