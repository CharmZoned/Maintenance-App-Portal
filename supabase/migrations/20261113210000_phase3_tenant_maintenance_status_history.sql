-- Phase 3: tenant maintenance portal + status history + approve linked tenants
-- Additive. Does not alter inquiries.
--
-- - Status history table + trigger on MaintenanceRequests
-- - Admin-only Accept & schedule (Scheduled / scheduled_for) for non-admins
-- - Approve / role gates: linked tenants (tenant_id) can access tenant shell
-- - Harden current_tenant_unit_id / current_tenant_property_id to require approved
-- - FORCE RLS on photos/comments/history

-- ── Status history ────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public."MaintenanceRequestStatusHistory" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  maintenance_request_id bigint NOT NULL
    REFERENCES public."MaintenanceRequests"(id) ON DELETE CASCADE,
  from_status text,
  to_status text NOT NULL,
  changed_by_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  changed_by_role public.app_role,
  note text
);

CREATE INDEX IF NOT EXISTS maintenance_request_status_history_request_idx
  ON public."MaintenanceRequestStatusHistory" (maintenance_request_id, created_at DESC);

ALTER TABLE public."MaintenanceRequestStatusHistory" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."MaintenanceRequestStatusHistory" FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS maintenance_status_history_select ON public."MaintenanceRequestStatusHistory";
CREATE POLICY maintenance_status_history_select
  ON public."MaintenanceRequestStatusHistory"
  FOR SELECT
  TO authenticated
  USING (
    private.can_select_maintenance_request(maintenance_request_id)
  );

-- No client INSERT/UPDATE/DELETE — rows come from SECURITY DEFINER trigger only.

CREATE OR REPLACE FUNCTION private.log_maintenance_status_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_role public.app_role;
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO public."MaintenanceRequestStatusHistory" (
      maintenance_request_id,
      from_status,
      to_status,
      changed_by_user_id,
      changed_by_role,
      note
    ) VALUES (
      NEW.id,
      NULL,
      NEW.status,
      auth.uid(),
      private.current_role(),
      'Created'
    );
    RETURN NEW;
  END IF;

  IF NEW.status IS DISTINCT FROM OLD.status THEN
    BEGIN
      v_role := private.current_role();
    EXCEPTION WHEN OTHERS THEN
      v_role := NULL;
    END;

    INSERT INTO public."MaintenanceRequestStatusHistory" (
      maintenance_request_id,
      from_status,
      to_status,
      changed_by_user_id,
      changed_by_role,
      note
    ) VALUES (
      NEW.id,
      OLD.status,
      NEW.status,
      auth.uid(),
      v_role,
      NULL
    );
  END IF;

  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS trg_maintenance_status_history_ins ON public."MaintenanceRequests";
CREATE TRIGGER trg_maintenance_status_history_ins
  AFTER INSERT ON public."MaintenanceRequests"
  FOR EACH ROW
  EXECUTE FUNCTION private.log_maintenance_status_change();

DROP TRIGGER IF EXISTS trg_maintenance_status_history_upd ON public."MaintenanceRequests";
CREATE TRIGGER trg_maintenance_status_history_upd
  AFTER UPDATE OF status ON public."MaintenanceRequests"
  FOR EACH ROW
  EXECUTE FUNCTION private.log_maintenance_status_change();

COMMENT ON TABLE public."MaintenanceRequestStatusHistory" IS
  'Append-only status trail for MaintenanceRequests; written by trigger only.';

-- ── Admin-only Accept & schedule ──────────────────────────────────

CREATE OR REPLACE FUNCTION private.protect_maintenance_request()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_role public.app_role;
BEGIN
  IF auth.uid() IS NULL THEN
    RETURN NEW;
  END IF;

  v_role := private.current_role();

  IF v_role = 'admin'::public.app_role THEN
    RETURN NEW;
  END IF;

  IF NEW.id IS DISTINCT FROM OLD.id
    OR NEW.request_number IS DISTINCT FROM OLD.request_number
    OR NEW.unit_id IS DISTINCT FROM OLD.unit_id
    OR NEW.submitted_by_tenant_id IS DISTINCT FROM OLD.submitted_by_tenant_id
    OR NEW.title IS DISTINCT FROM OLD.title
    OR NEW.description IS DISTINCT FROM OLD.description
    OR NEW.category IS DISTINCT FROM OLD.category
    OR NEW.created_at IS DISTINCT FROM OLD.created_at
    OR NEW.is_test_data IS DISTINCT FROM OLD.is_test_data
    OR NEW.location IS DISTINCT FROM OLD.location
    OR NEW.permission_to_enter IS DISTINCT FROM OLD.permission_to_enter
    OR NEW.client_submission_id IS DISTINCT FROM OLD.client_submission_id
  THEN
    RAISE EXCEPTION 'These request fields cannot be changed from this account';
  END IF;

  IF v_role = 'maintenance'::public.app_role
    AND NEW.assigned_staff_id IS DISTINCT FROM OLD.assigned_staff_id
  THEN
    RAISE EXCEPTION 'Assigned staff cannot be changed from this account';
  END IF;

  -- Accept & schedule is admin-only (Phase 3)
  IF NEW.scheduled_for IS DISTINCT FROM OLD.scheduled_for
    OR (
      NEW.status IS DISTINCT FROM OLD.status
      AND NEW.status = 'Scheduled'
    )
  THEN
    RAISE EXCEPTION 'Only admins can Accept & schedule maintenance requests';
  END IF;

  RETURN NEW;
END;
$function$;

COMMENT ON FUNCTION private.protect_maintenance_request() IS
  'Blocks non-admins from rewriting submission fields; maintenance cannot reassign; Accept & schedule is admin-only.';

-- ── Harden tenant scope helpers ───────────────────────────────────

CREATE OR REPLACE FUNCTION private.current_tenant_unit_id()
RETURNS bigint
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
  SELECT tenant.unit_id
  FROM public.user_roles AS membership
  JOIN public."Tenants" AS tenant ON tenant.id = membership.tenant_id
  WHERE membership.user_id = (SELECT auth.uid())
    AND membership.account_status = 'approved'
    AND membership.role = 'tenant'::public.app_role
$function$;

CREATE OR REPLACE FUNCTION private.current_tenant_property_id()
RETURNS bigint
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
  SELECT unit.property_id
  FROM public.user_roles AS membership
  JOIN public."Tenants" AS tenant ON tenant.id = membership.tenant_id
  JOIN public."Units" AS unit ON unit.id = tenant.unit_id
  WHERE membership.user_id = (SELECT auth.uid())
    AND membership.account_status = 'approved'
    AND membership.role = 'tenant'::public.app_role
$function$;

-- ── Approve linked tenants for tenant shell ───────────────────────

CREATE OR REPLACE FUNCTION public.set_account_status(
  p_user_id uuid,
  p_status text
)
RETURNS public.user_roles
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  result public.user_roles;
BEGIN
  IF NOT private.is_admin() THEN
    RAISE EXCEPTION 'Only admins can change account status';
  END IF;

  IF p_status IS NULL OR p_status NOT IN ('pending', 'approved', 'rejected', 'suspended') THEN
    RAISE EXCEPTION 'Invalid account_status: %', p_status;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM auth.users WHERE id = p_user_id) THEN
    RAISE EXCEPTION 'Auth user % not found', p_user_id;
  END IF;

  IF p_status = 'approved' THEN
    SELECT * INTO result FROM public.user_roles WHERE user_id = p_user_id;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Assign a role before approving';
    END IF;
    IF result.role = 'admin'::public.app_role THEN
      NULL;
    ELSIF result.role = 'maintenance'::public.app_role AND result.staff_id IS NOT NULL THEN
      NULL;
    ELSIF result.role = 'tenant'::public.app_role AND result.tenant_id IS NOT NULL THEN
      NULL;
    ELSE
      RAISE EXCEPTION
        'Only admin, maintenance with Staff link, or tenant with Tenant link can be approved';
    END IF;

    UPDATE public.user_roles
    SET account_status = 'approved'
    WHERE user_id = p_user_id
    RETURNING * INTO result;

    RETURN result;
  END IF;

  INSERT INTO public.user_roles (user_id, role, account_status)
  VALUES (p_user_id, 'maintenance'::public.app_role, p_status)
  ON CONFLICT (user_id) DO UPDATE
    SET account_status = EXCLUDED.account_status
  RETURNING * INTO result;

  RETURN result;
END;
$function$;

COMMENT ON FUNCTION public.set_account_status IS
  'Admin-only account_status change. Approve requires admin, maintenance+staff_id, or tenant+tenant_id.';

CREATE OR REPLACE FUNCTION public.admin_set_user_role(
  p_user_id uuid,
  p_role public.app_role,
  p_landlord_id bigint DEFAULT NULL,
  p_tenant_id bigint DEFAULT NULL,
  p_staff_id bigint DEFAULT NULL
)
RETURNS public.user_roles
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  result public.user_roles;
  v_landlord bigint;
  v_tenant bigint;
  v_staff bigint;
  v_status text;
BEGIN
  IF NOT private.is_admin() THEN
    RAISE EXCEPTION 'Only admins can assign user roles';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM auth.users WHERE id = p_user_id) THEN
    RAISE EXCEPTION 'Auth user % not found', p_user_id;
  END IF;

  v_landlord := NULL;
  v_tenant := NULL;
  v_staff := NULL;

  IF p_role = 'admin'::public.app_role THEN
    NULL;
  ELSIF p_role = 'landlord'::public.app_role THEN
    v_landlord := p_landlord_id;
  ELSIF p_role = 'tenant'::public.app_role THEN
    v_tenant := p_tenant_id;
  ELSIF p_role = 'maintenance'::public.app_role THEN
    v_staff := p_staff_id;
  ELSE
    RAISE EXCEPTION 'Unsupported role: %', p_role;
  END IF;

  SELECT account_status INTO v_status
  FROM public.user_roles
  WHERE user_id = p_user_id;

  IF COALESCE(v_status, 'pending') = 'approved' THEN
    IF p_role = 'maintenance'::public.app_role AND v_staff IS NULL THEN
      RAISE EXCEPTION
        'Cannot clear Staff link while approved; suspend or reject first, or keep a Staff link';
    END IF;
    IF p_role = 'tenant'::public.app_role AND v_tenant IS NULL THEN
      RAISE EXCEPTION
        'Cannot clear Tenant link while approved; suspend or reject first, or keep a Tenant link';
    END IF;
    IF p_role = 'landlord'::public.app_role THEN
      RAISE EXCEPTION
        'Cannot assign landlord while approved; suspend or reject first (landlord portal not shipped)';
    END IF;
  END IF;

  INSERT INTO public.user_roles (
    user_id, role, landlord_id, tenant_id, staff_id, account_status
  )
  VALUES (
    p_user_id,
    p_role,
    v_landlord,
    v_tenant,
    v_staff,
    COALESCE(v_status, 'pending')
  )
  ON CONFLICT (user_id) DO UPDATE
    SET role = EXCLUDED.role,
        landlord_id = EXCLUDED.landlord_id,
        tenant_id = EXCLUDED.tenant_id,
        staff_id = EXCLUDED.staff_id
  RETURNING * INTO result;

  RETURN result;
END;
$function$;

COMMENT ON FUNCTION public.admin_set_user_role IS
  'Admin assigns role + link ids. Approved maintenance needs staff_id; approved tenant needs tenant_id; landlord portal still blocked while approved.';

