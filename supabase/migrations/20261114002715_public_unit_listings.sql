create view public.website_listings
with (security_invoker = true) as
select
  u.source_id,
  u.listing_headline,
  u.listing_description,
  u.neighborhood,
  u.available_on,
  u.inquiry_email,
  u.inquiry_phone,
  u.market_rent,
  u.bedrooms,
  u.bathrooms,
  u.sqft,
  u.unit_label,
  u.listing_property_type,
  p.street_address,
  p.city,
  p.state,
  p.zip,
  p.property_type,
  (
    select coalesce(
      jsonb_agg(
        jsonb_build_object(
          'storage_path', ph.storage_path,
          'alt_text', ph.alt_text,
          'width', ph.width,
          'height', ph.height,
          'sort_order', ph.sort_order
        )
        order by ph.sort_order, ph.id
      ),
      '[]'::jsonb
    )
    from public."UnitListingPhotos" ph
    where ph.unit_id = u.id
  ) as photos
from public."Units" u
join public."Properties" p on p.id = u.property_id
where u.currently_being_marketed
  and u.is_test_data = false
  and p.is_test_data = false
  and u.management_status = 'Active'
  and u.readiness_status <> all (array['Rehab Needed'::text, 'Rehab In Progress'::text])
  and u.market_rent > 0
  and nullif(btrim(u.listing_headline), '') is not null
  and nullif(btrim(u.listing_description), '') is not null
  and p.property_type <> 'Commercial'
  and (
    p.property_type in (
      'Single-family', 'Townhouse', 'Condo', 'Apartment building', 'Multi-family'
    )
    or (p.property_type = 'Other' and u.listing_property_type is not null)
  )
  and exists (
    select 1
    from public."UnitListingPhotos" ph
    where ph.unit_id = u.id
  );

comment on view public.website_listings is
  'Marketed units safe to render on the public website. No notes, landlord, tenant, lease, or application columns.';

