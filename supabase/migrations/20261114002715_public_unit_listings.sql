-- Marketing stays an explicit choice, and only after the public copy, a
-- positive asking rent, a residential type, and a real photo are present.
create or replace function private.enforce_marketed_unit_listing()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  property_type text;
begin
  if not new.currently_being_marketed then
    return new;
  end if;

  if new.market_rent is null or new.market_rent <= 0 then
    raise exception 'A marketed unit needs a market rent greater than 0';
  end if;

  if new.listing_headline is null or length(btrim(new.listing_headline)) = 0 then
    raise exception 'A marketed unit needs a public headline';
  end if;

  if new.listing_description is null or length(btrim(new.listing_description)) = 0 then
    raise exception 'A marketed unit needs a public description';
  end if;

  select p.property_type into property_type
  from public."Properties" p
  where p.id = new.property_id;

  if property_type is null or property_type = 'Commercial' then
    raise exception 'Commercial properties are not published as website listings';
  end if;

  if property_type = 'Other' and new.listing_property_type is null then
    raise exception 'Choose a website property type before marketing this unit';
  end if;

  if property_type not in (
    'Single-family', 'Townhouse', 'Condo', 'Apartment building', 'Multi-family', 'Other'
  ) then
    raise exception 'This property type cannot be published as a website listing';
  end if;

  if tg_op = 'INSERT' or not exists (
    select 1 from public."UnitListingPhotos" ph where ph.unit_id = new.id
  ) then
    raise exception 'A marketed unit needs at least one public photo';
  end if;

  return new;
end;
$$;

create trigger units_enforce_marketed_listing
  before insert or update of currently_being_marketed, market_rent, listing_headline,
    listing_description, listing_property_type, property_id
  on public."Units"
  for each row
  execute function private.enforce_marketed_unit_listing();

create or replace function private.keep_last_listing_photo()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  marketed boolean;
  remaining integer;
begin
  if tg_op = 'DELETE' or (tg_op = 'UPDATE' and new.unit_id is distinct from old.unit_id) then
    select u.currently_being_marketed into marketed
    from public."Units" u
    where u.id = old.unit_id;

    if coalesce(marketed, false) then
      select count(*) into remaining
      from public."UnitListingPhotos" ph
      where ph.unit_id = old.unit_id
        and ph.id <> old.id;

      if remaining < 1 then
        raise exception 'A marketed unit needs at least one public photo';
      end if;
    end if;
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

