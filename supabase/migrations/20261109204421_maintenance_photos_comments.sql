  ON public."MaintenanceRequests"
  FOR INSERT
  TO authenticated
  WITH CHECK ((SELECT private.current_role()) = 'admin'::public.app_role);

DROP POLICY IF EXISTS maintenance_photos_select ON public."MaintenanceRequestPhotos";
CREATE POLICY maintenance_photos_select
  ON public."MaintenanceRequestPhotos"
  FOR SELECT
  TO authenticated
  USING ((SELECT private.can_select_maintenance_request(maintenance_request_id)));

DROP POLICY IF EXISTS maintenance_photos_insert ON public."MaintenanceRequestPhotos";
CREATE POLICY maintenance_photos_insert
  ON public."MaintenanceRequestPhotos"
  FOR INSERT
  TO authenticated
  WITH CHECK ((SELECT private.can_upload_maintenance_photo(maintenance_request_id)));

DROP POLICY IF EXISTS maintenance_photos_delete ON public."MaintenanceRequestPhotos";
CREATE POLICY maintenance_photos_delete
  ON public."MaintenanceRequestPhotos"
  FOR DELETE
  TO authenticated
  USING (
    (SELECT private.current_role()) = 'admin'::public.app_role
    OR (
      (SELECT private.current_role()) = 'tenant'::public.app_role
      AND uploaded_by_user_id = auth.uid()
      AND (SELECT private.can_upload_maintenance_photo(maintenance_request_id))
    )
  );

DROP POLICY IF EXISTS maintenance_comments_select ON public."MaintenanceRequestComments";
CREATE POLICY maintenance_comments_select
  ON public."MaintenanceRequestComments"
  FOR SELECT
  TO authenticated
  USING (
    (SELECT private.can_select_maintenance_request(maintenance_request_id))
    AND (
      visibility = 'tenant_visible'
      OR (SELECT private.current_role()) IN ('admin'::public.app_role, 'landlord'::public.app_role, 'maintenance'::public.app_role)
    )
  );

DROP POLICY IF EXISTS maintenance_comments_insert ON public."MaintenanceRequestComments";
CREATE POLICY maintenance_comments_insert
  ON public."MaintenanceRequestComments"
  FOR INSERT
  TO authenticated
  WITH CHECK (
    (SELECT private.can_update_maintenance_request(maintenance_request_id))
    AND visibility IN ('tenant_visible', 'internal')
  );

DROP POLICY IF EXISTS maintenance_comments_delete ON public."MaintenanceRequestComments";
CREATE POLICY maintenance_comments_delete
  ON public."MaintenanceRequestComments"
  FOR DELETE
  TO authenticated
  USING ((SELECT private.current_role()) = 'admin'::public.app_role);

