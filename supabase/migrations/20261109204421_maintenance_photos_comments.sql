-- Keeps existing MaintenanceRequests status machine unchanged.

ALTER TABLE public."MaintenanceRequests"
  ADD COLUMN IF NOT EXISTS location text,
  ADD COLUMN IF NOT EXISTS permission_to_enter boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS client_submission_id uuid;

CREATE UNIQUE INDEX IF NOT EXISTS maintenance_requests_client_submission_id_key
  ON public."MaintenanceRequests"(client_submission_id)
  WHERE client_submission_id IS NOT NULL;

CREATE OR REPLACE FUNCTION private.protect_maintenance_request()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
begin
  if auth.uid() is null or (select private.current_role()) = 'admin' then
    return new;
  end if;

  if new.id is distinct from old.id
    or new.request_number is distinct from old.request_number
    or new.unit_id is distinct from old.unit_id
    or new.submitted_by_tenant_id is distinct from old.submitted_by_tenant_id
    or new.title is distinct from old.title
    or new.description is distinct from old.description
    or new.category is distinct from old.category
    or new.created_at is distinct from old.created_at
    or new.is_test_data is distinct from old.is_test_data
    or new.location is distinct from old.location
    or new.permission_to_enter is distinct from old.permission_to_enter
    or new.client_submission_id is distinct from old.client_submission_id
  then
    raise exception 'These request fields cannot be changed from this account';
  end if;

  if (select private.current_role()) = 'maintenance'
    and new.assigned_staff_id is distinct from old.assigned_staff_id
  then
    raise exception 'Assigned staff cannot be changed from this account';
  end if;

  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION private.can_select_maintenance_request(target_request bigint)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public."MaintenanceRequests" AS request
    WHERE request.id = target_request
      AND (
        (SELECT private.current_role()) = 'admin'::public.app_role
        OR request.submitted_by_tenant_id = (SELECT private.current_tenant_id())
        OR request.assigned_staff_id = (SELECT private.current_staff_id())
        OR (SELECT private.landlord_owns_unit(request.unit_id))
      )
  );
$$;

CREATE OR REPLACE FUNCTION private.can_update_maintenance_request(target_request bigint)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public."MaintenanceRequests" AS request
    WHERE request.id = target_request
      AND (
        (SELECT private.current_role()) = 'admin'::public.app_role
        OR (
          (SELECT private.current_role()) = 'landlord'::public.app_role
          AND (SELECT private.landlord_owns_unit(request.unit_id))
        )
        OR (
          (SELECT private.current_role()) = 'maintenance'::public.app_role
          AND request.assigned_staff_id = (SELECT private.current_staff_id())
        )
      )
  );
$$;

CREATE OR REPLACE FUNCTION private.can_upload_maintenance_photo(target_request bigint)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public."MaintenanceRequests" AS request
    WHERE request.id = target_request
      AND (
        (SELECT private.can_update_maintenance_request(target_request))
        OR (
          (SELECT private.current_role()) = 'tenant'::public.app_role
          AND request.submitted_by_tenant_id = (SELECT private.current_tenant_id())
        )
      )
  );
$$;

REVOKE ALL ON FUNCTION private.can_select_maintenance_request(bigint) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION private.can_update_maintenance_request(bigint) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION private.can_upload_maintenance_photo(bigint) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION private.can_select_maintenance_request(bigint) TO authenticated, service_role;
GRANT EXECUTE ON FUNCTION private.can_update_maintenance_request(bigint) TO authenticated, service_role;
GRANT EXECUTE ON FUNCTION private.can_upload_maintenance_photo(bigint) TO authenticated, service_role;

CREATE TABLE IF NOT EXISTS public."MaintenanceRequestPhotos" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  maintenance_request_id bigint NOT NULL
    REFERENCES public."MaintenanceRequests"(id) ON DELETE CASCADE,
  storage_path text NOT NULL,
  uploaded_by_role public.app_role,
  uploaded_by_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  caption text,
  CONSTRAINT maintenance_request_photos_path_check CHECK (length(trim(storage_path)) > 0)
);

CREATE INDEX IF NOT EXISTS idx_maintenance_request_photos_request
  ON public."MaintenanceRequestPhotos"(maintenance_request_id);

ALTER TABLE public."MaintenanceRequestPhotos" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."MaintenanceRequestPhotos" FORCE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS public."MaintenanceRequestComments" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  maintenance_request_id bigint NOT NULL
    REFERENCES public."MaintenanceRequests"(id) ON DELETE CASCADE,
  author_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  author_role public.app_role,
  author_staff_id bigint REFERENCES public."Staff"(id) ON DELETE SET NULL,
  author_tenant_id bigint REFERENCES public."Tenants"(id) ON DELETE SET NULL,
  body text NOT NULL,
  visibility text NOT NULL DEFAULT 'tenant_visible'
    CHECK (visibility = ANY (ARRAY['tenant_visible'::text, 'internal'::text])),
  CONSTRAINT maintenance_request_comments_body_check CHECK (length(trim(body)) > 0)
);

CREATE INDEX IF NOT EXISTS idx_maintenance_request_comments_request
  ON public."MaintenanceRequestComments"(maintenance_request_id, created_at);

ALTER TABLE public."MaintenanceRequestComments" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."MaintenanceRequestComments" FORCE ROW LEVEL SECURITY;

