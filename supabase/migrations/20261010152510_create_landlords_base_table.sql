-- Create the base "Landlords" table that the first tracked migration
-- (20261010152511_setup_data_intake_tables) ALTERs.
--
-- On production the table was created in the Supabase dashboard before
-- migrations were tracked, so no file ever created it and a database built
-- from supabase/migrations/ alone (the staging rebuild) failed on the first
-- file. This records the dashboard-created shape: an identity id and
-- created_at. Every other column is added by 20261010152511.
--
-- The version is deliberately one second before 20261010152511 so it runs
-- first. On production the table already exists, so this is a no-op there;
-- production's history only needs the version recorded, without running DDL:
--   supabase migration repair --remote --yes --status applied 20261010152510
-- (see docs/ops/schema-migrations.md).

CREATE TABLE IF NOT EXISTS public."Landlords" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now()
);
