-- App fields and tables for LG Maintenance Portal ↔ Landlord Gopher.
-- Supabase stays source of truth for existing columns/values; this adds
-- the app's missing fields/tables and merges work orders into MaintenanceRequests.

-- ── Vendors first (FK target for MaintenanceRequests.vendor_id) ─────
CREATE TABLE IF NOT EXISTS public."Vendors" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  name text NOT NULL,
  category text NOT NULL DEFAULT 'general'
    CHECK (category = ANY (ARRAY[
      'plumber'::text, 'electrician'::text, 'hvac'::text, 'handyman'::text,
      'cleaning'::text, 'landscaping'::text, 'general'::text
    ])),
  phone text,
  email text,
  notes text,
  color text NOT NULL DEFAULT 'slate',
  is_test_data boolean NOT NULL DEFAULT false
);

ALTER TABLE public."Vendors" ENABLE ROW LEVEL SECURITY;

-- ── Extra columns on existing tables ────────────────────────────────
ALTER TABLE public."Properties"
  ADD COLUMN IF NOT EXISTS year_built integer,
  ADD COLUMN IF NOT EXISTS color text NOT NULL DEFAULT 'sky';

ALTER TABLE public."Units"
  ADD COLUMN IF NOT EXISTS sqft integer,
  ADD COLUMN IF NOT EXISTS market_rent numeric NOT NULL DEFAULT 0;

ALTER TABLE public."Tenants"
  ADD COLUMN IF NOT EXISTS date_of_birth date,
  ADD COLUMN IF NOT EXISTS emergency_contact text,
  ADD COLUMN IF NOT EXISTS employer text,
  ADD COLUMN IF NOT EXISTS monthly_income numeric;

-- source_id defaults so app-created rows satisfy the unique NOT NULL column
ALTER TABLE public."Landlords"
  ALTER COLUMN source_id SET DEFAULT ('app-' || gen_random_uuid()::text);
ALTER TABLE public."Properties"
  ALTER COLUMN source_id SET DEFAULT ('app-' || gen_random_uuid()::text);
ALTER TABLE public."Units"
  ALTER COLUMN source_id SET DEFAULT ('app-' || gen_random_uuid()::text);
ALTER TABLE public."Tenants"
  ALTER COLUMN source_id SET DEFAULT ('app-' || gen_random_uuid()::text);

-- ── MaintenanceRequests absorbs work orders ─────────────────────────
ALTER TABLE public."MaintenanceRequests"
  ADD COLUMN IF NOT EXISTS property_id bigint REFERENCES public."Properties"(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS vendor_id bigint REFERENCES public."Vendors"(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS cost numeric,
  ADD COLUMN IF NOT EXISTS notes text;

ALTER TABLE public."MaintenanceRequests"
  ALTER COLUMN unit_id DROP NOT NULL,
  ALTER COLUMN submitted_by_tenant_id DROP NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'maintenance_requests_unit_or_property'
  ) THEN
    ALTER TABLE public."MaintenanceRequests"
      ADD CONSTRAINT maintenance_requests_unit_or_property
      CHECK (unit_id IS NOT NULL OR property_id IS NOT NULL);
  END IF;
END $$;

-- ── New app tables ──────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public."Leases" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  unit_id bigint NOT NULL REFERENCES public."Units"(id) ON DELETE CASCADE,
  primary_tenant_id bigint REFERENCES public."Tenants"(id) ON DELETE SET NULL,
  start_date date NOT NULL,
  end_date date NOT NULL,
  monthly_rent numeric NOT NULL DEFAULT 0,
  deposit numeric NOT NULL DEFAULT 0,
  rent_due_day integer NOT NULL DEFAULT 1 CHECK (rent_due_day BETWEEN 1 AND 31),
  late_fee numeric NOT NULL DEFAULT 0,
  status text NOT NULL DEFAULT 'active'
    CHECK (status = ANY (ARRAY['upcoming'::text, 'active'::text, 'ended'::text, 'cancelled'::text])),
  notes text,
  is_test_data boolean NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS idx_leases_unit ON public."Leases"(unit_id);
CREATE INDEX IF NOT EXISTS idx_leases_tenant ON public."Leases"(primary_tenant_id);
CREATE INDEX IF NOT EXISTS idx_leases_status ON public."Leases"(status);

CREATE TABLE IF NOT EXISTS public."LeaseTenants" (
  lease_id bigint NOT NULL REFERENCES public."Leases"(id) ON DELETE CASCADE,
  tenant_id bigint NOT NULL REFERENCES public."Tenants"(id) ON DELETE CASCADE,
  PRIMARY KEY (lease_id, tenant_id)
);

CREATE TABLE IF NOT EXISTS public."RentCharges" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  lease_id bigint NOT NULL REFERENCES public."Leases"(id) ON DELETE CASCADE,
  period text NOT NULL CHECK (period ~ '^\d{4}-\d{2}$'),
  due_date date NOT NULL,
  amount numeric NOT NULL DEFAULT 0,
  amount_paid numeric NOT NULL DEFAULT 0,
  status text NOT NULL DEFAULT 'open'
    CHECK (status = ANY (ARRAY['open'::text, 'partial'::text, 'paid'::text, 'overdue'::text, 'waived'::text])),
  notes text,
  is_test_data boolean NOT NULL DEFAULT false,
  UNIQUE (lease_id, period)
);

CREATE INDEX IF NOT EXISTS idx_rent_charges_due ON public."RentCharges"(due_date);
CREATE INDEX IF NOT EXISTS idx_rent_charges_status ON public."RentCharges"(status);

CREATE TABLE IF NOT EXISTS public."Payments" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  charge_id bigint NOT NULL REFERENCES public."RentCharges"(id) ON DELETE CASCADE,
  paid_at timestamptz NOT NULL DEFAULT now(),
  amount numeric NOT NULL DEFAULT 0,
  method text NOT NULL DEFAULT 'cash'
    CHECK (method = ANY (ARRAY['cash'::text, 'check'::text, 'ach'::text, 'credit'::text, 'other'::text])),
  reference text,
  notes text,
  is_test_data boolean NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS idx_payments_charge ON public."Payments"(charge_id);

CREATE TABLE IF NOT EXISTS public."Applications" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  unit_id bigint REFERENCES public."Units"(id) ON DELETE SET NULL,
  first_name text NOT NULL,
  last_name text NOT NULL,
  email text,
  phone text,
  monthly_income numeric,
  employer text,
  desired_move_in date,
  status text NOT NULL DEFAULT 'new'
    CHECK (status = ANY (ARRAY['new'::text, 'screening'::text, 'approved'::text, 'declined'::text, 'withdrawn'::text])),
  notes text,
  is_test_data boolean NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS idx_applications_status ON public."Applications"(status);

CREATE TABLE IF NOT EXISTS public."Settings" (
  key text PRIMARY KEY,
  value text NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public."Leases" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."LeaseTenants" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."RentCharges" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."Payments" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."Applications" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."Settings" ENABLE ROW LEVEL SECURITY;
