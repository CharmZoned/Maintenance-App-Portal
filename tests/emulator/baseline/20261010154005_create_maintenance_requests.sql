CREATE TABLE public."MaintenanceRequests" (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 request_number text NOT NULL UNIQUE,
 unit_id bigint NOT NULL REFERENCES public."Units"(id),
 submitted_by_tenant_id bigint NOT NULL REFERENCES public."Tenants"(id),
 title text NOT NULL CHECK (length(trim(title))>0),
 description text NOT NULL CHECK (length(trim(description))>0),
 category text NOT NULL CHECK (category IN ('Plumbing','Electrical','Heating / AC','Appliance','Pest control','Locks / keys / doors','Windows','Roof / leaks','Mold / water damage','Exterior / yard','General repair','Other')),
 priority text NOT NULL DEFAULT 'Normal' CHECK (priority IN ('Low','Normal','High','Urgent')),
 status text NOT NULL DEFAULT 'Open' CHECK (status IN ('Open','Scheduled','In Progress','On Hold','Closed')),
 assigned_staff_id bigint REFERENCES public."Staff"(id),
 created_at timestamptz NOT NULL DEFAULT now(),
 scheduled_for timestamptz,
 started_at timestamptz,
 hold_reason text,
 next_follow_up_date date,
 closed_at timestamptz,
 resolution_notes text,
 is_test_data boolean NOT NULL DEFAULT false,
 CONSTRAINT requests_hold_details CHECK (status<>'On Hold' OR (hold_reason IS NOT NULL AND length(trim(hold_reason))>0 AND next_follow_up_date IS NOT NULL)),
 CONSTRAINT requests_closed_details CHECK ((status='Closed' AND closed_at IS NOT NULL AND resolution_notes IS NOT NULL AND length(trim(resolution_notes))>0) OR (status<>'Closed' AND closed_at IS NULL)),
 CONSTRAINT requests_scheduled_details CHECK (status<>'Scheduled' OR (assigned_staff_id IS NOT NULL AND scheduled_for IS NOT NULL)),
 CONSTRAINT requests_in_progress_details CHECK (status<>'In Progress' OR (assigned_staff_id IS NOT NULL AND started_at IS NOT NULL)),
 CONSTRAINT requests_started_after_created CHECK (started_at IS NULL OR started_at>=created_at),
 CONSTRAINT requests_closed_after_started CHECK (closed_at IS NULL OR closed_at>=coalesce(started_at,created_at))
);
CREATE INDEX maintenance_requests_unit_idx ON public."MaintenanceRequests"(unit_id);
CREATE INDEX maintenance_requests_tenant_idx ON public."MaintenanceRequests"(submitted_by_tenant_id);
CREATE INDEX maintenance_requests_staff_idx ON public."MaintenanceRequests"(assigned_staff_id);
CREATE INDEX maintenance_requests_status_idx ON public."MaintenanceRequests"(status);
ALTER TABLE public."MaintenanceRequests" ENABLE ROW LEVEL SECURITY;
