
ALTER TABLE public."Landlords"
 ADD COLUMN source_id text NOT NULL UNIQUE,
 ADD COLUMN first_name text NOT NULL,
 ADD COLUMN last_name text NOT NULL,
 ADD COLUMN company_name text,
 ADD COLUMN email text NOT NULL UNIQUE,
 ADD COLUMN mobile_phone text,
 ADD COLUMN preferred_contact text CHECK (preferred_contact IN ('Email','Phone','Either')),
 ADD COLUMN notes text,
 ADD COLUMN is_test_data boolean NOT NULL DEFAULT false;
CREATE TABLE public."Properties" (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at timestamptz NOT NULL DEFAULT now(),
 source_id text NOT NULL UNIQUE,
 property_name text,
 street_address text NOT NULL,
 city text NOT NULL,
 state text NOT NULL CHECK (state ~ '^[A-Z]{2}$'),
 zip text NOT NULL CHECK (zip ~ '^[0-9]{5}$'),
 property_type text NOT NULL CHECK (property_type IN ('Single-family','Multi-family','Condo','Townhouse','Apartment building','Commercial','Other')),
 landlord_id bigint NOT NULL REFERENCES public."Landlords"(id),
 notes text,
 is_test_data boolean NOT NULL DEFAULT false
);
CREATE INDEX properties_landlord_id_idx ON public."Properties"(landlord_id);
CREATE TABLE public."Units" (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at timestamptz NOT NULL DEFAULT now(),
 source_id text NOT NULL UNIQUE,
 property_id bigint NOT NULL REFERENCES public."Properties"(id),
 unit_label text NOT NULL,
 bedrooms integer CHECK (bedrooms >= 0),
 bathrooms numeric(4,1) CHECK (bathrooms > 0),
 status text NOT NULL CHECK (status IN ('Occupied','Vacant')),
 notes text,
 is_test_data boolean NOT NULL DEFAULT false,
 UNIQUE(property_id,unit_label)
);
CREATE TABLE public."Tenants" (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at timestamptz NOT NULL DEFAULT now(),
 source_id text NOT NULL UNIQUE,
 first_name text NOT NULL,
 last_name text NOT NULL,
 email text NOT NULL UNIQUE,
 mobile_phone text,
 unit_id bigint NOT NULL REFERENCES public."Units"(id),
 primary_on_lease boolean NOT NULL,
 invite_to_app boolean NOT NULL,
 notes text,
 is_test_data boolean NOT NULL DEFAULT false
);
CREATE INDEX tenants_unit_id_idx ON public."Tenants"(unit_id);
CREATE UNIQUE INDEX tenants_one_primary_per_unit_idx ON public."Tenants"(unit_id) WHERE primary_on_lease;
CREATE TABLE public."Staff" (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at timestamptz NOT NULL DEFAULT now(),
 first_name text NOT NULL,
 last_name text NOT NULL,
 email text NOT NULL UNIQUE,
 job_title text,
 gets_request_alerts boolean NOT NULL,
 is_test_data boolean NOT NULL DEFAULT false
);
CREATE TABLE public."Categories" (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at timestamptz NOT NULL DEFAULT now(),
 maintenance_category text NOT NULL UNIQUE,
 keep boolean NOT NULL,
 notes text,
 is_test_data boolean NOT NULL DEFAULT false
);
